-- Search synonyms: names shoppers use for the same thing (English, Japanese, nicknames, shorthand). A search for any term of a
-- group also finds products that only use another term of it ("初音ミク" finds "Hatsune Miku"). Staff edit them in Admin > Search;
-- the server reads them on start and again whenever they change. Terms are compared folded (lower case, no accents, ASCII
-- punctuation as spaces), so they're stored as typed. The rows below are the starting set.
create table if not exists public.search_synonyms (
  id uuid primary key default gen_random_uuid(),
  kind text not null default 'other' check (kind in ('type', 'series', 'maker', 'other')),
  terms text[] not null check (cardinality(terms) between 2 and 12),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists search_synonyms_kind_idx on public.search_synonyms (kind);

alter table public.search_synonyms enable row level security;

